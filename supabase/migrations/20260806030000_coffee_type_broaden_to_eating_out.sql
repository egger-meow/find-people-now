-- =============================================================================
-- 「咖啡」擴大成「吃飯/咖啡/探店」（v1.42）
--
-- 產品決策：原本「咖啡」類型太窄，很多校外聚會（吃飯、咖啡廳、探店）本質上
-- 是同一種「約出去吃點東西、順便聊天」的局，硬分成好幾個類型只會稀釋配對池
-- （同第 5 節「新增類型前先比對既有類型」的既有精神——這裡是反過來，先把
-- 官方類型本身擴大涵蓋範圍，減少使用者之後各自提案「吃飯」「下午茶」「探店」
-- 這些其實是同一件事的重複類型）。改名不改 id，既有的 match_request/activity
-- 参照不受影響。
--
-- 人數上限比照第 12.1 節「人少的場合社交壓力更高」的既有精神反過來推：這類
-- 場合天生比運動類更適合稍大的隨性聚會，上限訂 6 人（比原本的 4 人寬，但仍
-- 遠低於「先聚了再說」的 20 人，畢竟還是要能坐同一桌）。最低人數比照
-- 20260806020000 那批「團體活動至少 3 人」的底線一起調（原本 2 人）。
-- =============================================================================

update activity_type
   set name = '吃飯/咖啡/探店',
       default_min_participants = 3,
       default_max_participants = 6,
       description = '約校外吃飯、喝咖啡、探新開的店，順便聊天。時間地點由發起人與成員自行協調。'
 where name = '咖啡';
