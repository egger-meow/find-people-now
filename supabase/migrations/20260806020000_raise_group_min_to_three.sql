-- =============================================================================
-- 團體活動最低人數從 2 人提高到 3 人（v1.41）
--
-- 產品決策：一對一/兩人小局的社交壓力與安全風險偏高（呼應第 12.1 節既有的
-- 低人數准入/確認機制、第 16 節開放問題 7），這裡直接把預設活動類型的
-- `default_min_participants` 底線從 2 提高到 3，不再讓使用者用選項卡選出
-- 2 人局（籃球/桌遊/先聚了再說本來就 ≥3，麻將固定 4 人，皆不受影響）。
--
-- 純資料調整，不改 schema/RPC——`min_participants ≤ 2` 的 New 等級准入
-- 與 `PENDING_CONFIRMATION` 確認機制（第 12.1 節）維持不變，之後若有 admin
-- 透過 Studio 手動核准某個低人數類型，這兩道既有防線仍然有效，不是死碼。
--
-- 羽球原本 `group_size_step = 2`（min=2/max=4 只產生「2 人」「4 人」兩個離散
-- 選項）——min 提高到 3 後，若不調整 step，`for (v = 3; v <= 4; v += 2)` 只會
-- 產生「3 人」一個選項，等於變相少了「4 人雙打」這個既有選項。改成連續模式
-- （`group_size_step = null`），min=3/max=4 產生「3 人」「4 人」兩個選項，
-- 不會因為這次底線調整意外少一個選項。
-- =============================================================================

update activity_type
   set default_min_participants = 3
 where name in ('羽球', '散步', '讀書', '跑步', '健身')
   and default_min_participants = 2;

update activity_type
   set group_size_step = null
 where name = '羽球';
